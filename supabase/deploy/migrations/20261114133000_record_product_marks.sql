DO $$
DECLARE
  v_new int;
  v_hit int;
  v_missing int;
  v_ambiguous int;
BEGIN
  SELECT count(*) FILTER (WHERE mark = 'NEW'),
         count(*) FILTER (WHERE mark = 'ХИТ')
    INTO v_new, v_hit
  FROM _tiffani_product_marks;

  IF v_new <> 183 OR v_hit <> 57 THEN
    RAISE EXCEPTION 'mark snapshot drifted: NEW %, ХИТ %', v_new, v_hit;
  END IF;

  SELECT count(*)
    INTO v_missing
  FROM _tiffani_product_marks AS snapshot
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.products AS product
    WHERE product.tilda_uid = snapshot.tilda_uid
  );

  IF v_missing <> 0 THEN
    RAISE EXCEPTION 'mark snapshot is missing % products', v_missing;
  END IF;

  SELECT count(*)
    INTO v_ambiguous
  FROM (
    SELECT snapshot.tilda_uid
    FROM _tiffani_product_marks AS snapshot
    JOIN public.products AS product
      ON product.tilda_uid = snapshot.tilda_uid
    GROUP BY snapshot.tilda_uid
    HAVING count(*) <> 1
  ) AS extra;

  IF v_ambiguous <> 0 THEN
    RAISE EXCEPTION 'mark snapshot matches % tilda_uid values more than once', v_ambiguous;
  END IF;
END $$;

UPDATE public.products AS product
SET mark = snapshot.mark
FROM _tiffani_product_marks AS snapshot
WHERE product.tilda_uid = snapshot.tilda_uid
  AND product.mark IS NULL;

COMMIT;
